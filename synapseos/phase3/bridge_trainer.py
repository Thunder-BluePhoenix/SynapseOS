"""
Phase 3 — Neural→Symbolic and Symbolic→Neural bridge training.

Two small classifiers that connect the neural layers to the Neurosymbolic core:

  Neural→Symbolic: embedding vector → graph query type + entity
      Input : latent vector from JEPA encoder (latent_dim)
      Output: (query_type, doctype, intent)
              query_type ∈ {retrieve, reason, plan, compute, validate}

  Symbolic→Neural: symbolic reasoning result → embedding vector
      Input : structured rule result (encoded as features)
      Output: embedding vector that the KAN + output synthesizer can consume

Training data: generated by synth_bridge_generator.py or via GPT-4 teacher.

Install:
    pip install torch  (already installed)

Run:
    python -m synapseos.phase3.bridge_trainer
    python -m synapseos.phase3.bridge_trainer --dry-run
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict, dataclass
from pathlib import Path

import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader, Dataset, random_split


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

@dataclass
class BridgeConfig:
    # Dimensions (must match JEPA output)
    latent_dim: int = 64
    symbolic_feature_dim: int = 32
    output_embed_dim: int = 64
    hidden_dim: int = 128
    # Query types for neural→symbolic routing
    query_types: list[str] = None    # set in __post_init__
    # Training
    n2s_data_path: str = "data/bridges/n2s_pairs.json"
    s2n_data_path: str = "data/bridges/s2n_pairs.json"
    output_dir: str = "data/checkpoints/bridges"
    num_epochs: int = 50
    batch_size: int = 64
    learning_rate: float = 1e-3
    val_split: float = 0.15

    def __post_init__(self):
        if self.query_types is None:
            self.query_types = ["retrieve", "reason", "plan", "compute", "validate"]

    def save(self, path: str) -> None:
        with open(path, "w") as f:
            json.dump(asdict(self), f, indent=2)


# ---------------------------------------------------------------------------
# Neural → Symbolic bridge
# ---------------------------------------------------------------------------

class NeuralToSymbolicBridge(nn.Module):
    """
    Routes a JEPA latent vector to a graph query.
    Outputs:
      - query_type logits (5 classes)
      - doctype logits (one per known DocType)
      - intent embedding (for query construction)
    """

    def __init__(self, cfg: BridgeConfig, num_doctypes: int):
        super().__init__()
        self.encoder = nn.Sequential(
            nn.Linear(cfg.latent_dim, cfg.hidden_dim),
            nn.GELU(),
            nn.LayerNorm(cfg.hidden_dim),
            nn.Linear(cfg.hidden_dim, cfg.hidden_dim),
            nn.GELU(),
        )
        self.query_type_head = nn.Linear(cfg.hidden_dim, len(cfg.query_types))
        self.doctype_head    = nn.Linear(cfg.hidden_dim, num_doctypes)
        self.intent_head     = nn.Linear(cfg.hidden_dim, cfg.output_embed_dim)

    def forward(self, latent: torch.Tensor):
        h = self.encoder(latent)
        return {
            "query_type_logits": self.query_type_head(h),
            "doctype_logits":    self.doctype_head(h),
            "intent_embed":      self.intent_head(h),
        }


# ---------------------------------------------------------------------------
# Symbolic → Neural bridge
# ---------------------------------------------------------------------------

class SymbolicToNeuralBridge(nn.Module):
    """
    Projects a symbolic reasoning result back into embedding space
    so the KAN layer and output synthesizer can consume it.

    Input: fixed-size feature vector representing the rule result:
      [confidence, rule_type_onehot (5), event_onehot (9), value_scalar, ...]
    Output: embedding vector (output_embed_dim)
    """

    def __init__(self, cfg: BridgeConfig):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(cfg.symbolic_feature_dim, cfg.hidden_dim),
            nn.GELU(),
            nn.LayerNorm(cfg.hidden_dim),
            nn.Linear(cfg.hidden_dim, cfg.hidden_dim),
            nn.GELU(),
            nn.Linear(cfg.hidden_dim, cfg.output_embed_dim),
            nn.LayerNorm(cfg.output_embed_dim),
        )

    def forward(self, symbolic_features: torch.Tensor) -> torch.Tensor:
        return self.net(symbolic_features)


# ---------------------------------------------------------------------------
# Datasets
# ---------------------------------------------------------------------------

class N2SDataset(Dataset):
    """
    Neural→Symbolic training pairs.
    JSON format:
        [{"latent": [...], "query_type": "retrieve", "doctype": "Sales Order"}, ...]
    """

    def __init__(self, data_path: str, query_types: list[str], doctype_index: dict[str, int]):
        with open(data_path) as f:
            records = json.load(f)

        self.latents     = []
        self.query_types = []
        self.doctypes    = []

        for rec in records:
            self.latents.append(rec["latent"])
            qt = rec.get("query_type", "retrieve")
            self.query_types.append(query_types.index(qt) if qt in query_types else 0)
            dt = rec.get("doctype", "")
            self.doctypes.append(doctype_index.get(dt, 0))

        self.latents     = torch.tensor(self.latents,     dtype=torch.float32)
        self.query_types = torch.tensor(self.query_types, dtype=torch.long)
        self.doctypes    = torch.tensor(self.doctypes,    dtype=torch.long)

    def __len__(self):
        return len(self.latents)

    def __getitem__(self, idx):
        return self.latents[idx], self.query_types[idx], self.doctypes[idx]


class S2NDataset(Dataset):
    """
    Symbolic→Neural training pairs.
    JSON format:
        [{"symbolic_features": [...], "target_embed": [...]}, ...]
    """

    def __init__(self, data_path: str):
        with open(data_path) as f:
            records = json.load(f)

        self.features = torch.tensor([r["symbolic_features"] for r in records], dtype=torch.float32)
        self.targets  = torch.tensor([r["target_embed"]      for r in records], dtype=torch.float32)

    def __len__(self):
        return len(self.features)

    def __getitem__(self, idx):
        return self.features[idx], self.targets[idx]


# ---------------------------------------------------------------------------
# Training
# ---------------------------------------------------------------------------

def train_n2s(cfg: BridgeConfig, device: torch.device) -> None:
    data_path = Path(cfg.n2s_data_path)
    if not data_path.exists():
        print(f"N2S data not found at {data_path}")
        print("Run: python -m synapseos.phase3.synth_bridge_generator")
        return

    with open(data_path) as f:
        records = json.load(f)

    all_doctypes   = sorted(set(r.get("doctype", "") for r in records))
    doctype_index  = {dt: i for i, dt in enumerate(all_doctypes)}
    num_doctypes   = len(all_doctypes)

    with open(f"{cfg.output_dir}/doctype_index.json", "w") as f:
        json.dump(doctype_index, f, indent=2)

    dataset = N2SDataset(cfg.n2s_data_path, cfg.query_types, doctype_index)
    val_size   = max(1, int(len(dataset) * cfg.val_split))
    train_ds, val_ds = random_split(dataset, [len(dataset) - val_size, val_size])

    train_loader = DataLoader(train_ds, batch_size=cfg.batch_size, shuffle=True)
    val_loader   = DataLoader(val_ds,   batch_size=cfg.batch_size)

    model = NeuralToSymbolicBridge(cfg, num_doctypes).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg.learning_rate)

    best_val_loss = float("inf")
    print(f"\nTraining Neural→Symbolic bridge  ({len(dataset)} pairs, {num_doctypes} DocTypes)")

    for epoch in range(1, cfg.num_epochs + 1):
        model.train()
        train_loss = 0.0
        for latents, qt_labels, dt_labels in train_loader:
            latents, qt_labels, dt_labels = latents.to(device), qt_labels.to(device), dt_labels.to(device)
            optimizer.zero_grad()
            out = model(latents)
            loss_qt = F.cross_entropy(out["query_type_logits"], qt_labels)
            loss_dt = F.cross_entropy(out["doctype_logits"],    dt_labels)
            loss    = loss_qt + 0.5 * loss_dt
            loss.backward()
            optimizer.step()
            train_loss += loss.item()
        train_loss /= len(train_loader)

        model.eval()
        val_loss = 0.0
        correct_qt = 0
        total = 0
        with torch.no_grad():
            for latents, qt_labels, dt_labels in val_loader:
                latents, qt_labels, dt_labels = latents.to(device), qt_labels.to(device), dt_labels.to(device)
                out = model(latents)
                loss_qt = F.cross_entropy(out["query_type_logits"], qt_labels)
                loss_dt = F.cross_entropy(out["doctype_logits"],    dt_labels)
                val_loss += (loss_qt + 0.5 * loss_dt).item()
                correct_qt += (out["query_type_logits"].argmax(1) == qt_labels).sum().item()
                total += len(qt_labels)
        val_loss /= len(val_loader)
        qt_acc = correct_qt / total * 100

        if epoch % 10 == 0 or epoch == 1:
            print(f"  Epoch {epoch:3d}/{cfg.num_epochs}  loss={val_loss:.4f}  qt_acc={qt_acc:.1f}%")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save(model.state_dict(), f"{cfg.output_dir}/n2s_best.pt")

    print(f"  Best N2S val loss: {best_val_loss:.4f} → {cfg.output_dir}/n2s_best.pt")


def train_s2n(cfg: BridgeConfig, device: torch.device) -> None:
    data_path = Path(cfg.s2n_data_path)
    if not data_path.exists():
        print(f"S2N data not found at {data_path}")
        print("Run: python -m synapseos.phase3.synth_bridge_generator")
        return

    dataset = S2NDataset(cfg.s2n_data_path)
    val_size   = max(1, int(len(dataset) * cfg.val_split))
    train_ds, val_ds = random_split(dataset, [len(dataset) - val_size, val_size])

    train_loader = DataLoader(train_ds, batch_size=cfg.batch_size, shuffle=True)
    val_loader   = DataLoader(val_ds,   batch_size=cfg.batch_size)

    model = SymbolicToNeuralBridge(cfg).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg.learning_rate)

    best_val_loss = float("inf")
    print(f"\nTraining Symbolic→Neural bridge  ({len(dataset)} pairs)")

    for epoch in range(1, cfg.num_epochs + 1):
        model.train()
        train_loss = 0.0
        for features, targets in train_loader:
            features, targets = features.to(device), targets.to(device)
            optimizer.zero_grad()
            pred = model(features)
            loss = F.mse_loss(pred, targets)
            loss.backward()
            optimizer.step()
            train_loss += loss.item()
        train_loss /= len(train_loader)

        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for features, targets in val_loader:
                features, targets = features.to(device), targets.to(device)
                pred = model(features)
                val_loss += F.mse_loss(pred, targets).item()
        val_loss /= len(val_loader)

        if epoch % 10 == 0 or epoch == 1:
            print(f"  Epoch {epoch:3d}/{cfg.num_epochs}  train={train_loss:.5f}  val={val_loss:.5f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save(model.state_dict(), f"{cfg.output_dir}/s2n_best.pt")

    print(f"  Best S2N val loss: {best_val_loss:.5f} → {cfg.output_dir}/s2n_best.pt")


def train(cfg: BridgeConfig) -> None:
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")
    Path(cfg.output_dir).mkdir(parents=True, exist_ok=True)
    cfg.save(f"{cfg.output_dir}/bridge_config.json")

    train_n2s(cfg, device)
    train_s2n(cfg, device)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output",  default="data/checkpoints/bridges")
    parser.add_argument("--epochs",  type=int,   default=50)
    parser.add_argument("--batch",   type=int,   default=64)
    parser.add_argument("--lr",      type=float, default=1e-3)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    cfg = BridgeConfig(
        output_dir=args.output,
        num_epochs=args.epochs,
        batch_size=args.batch,
        learning_rate=args.lr,
    )

    print("=== Bridge Trainer Config ===")
    for k, v in asdict(cfg).items():
        print(f"  {k}: {v}")

    if args.dry_run:
        return

    train(cfg)


if __name__ == "__main__":
    main()
